#!/usr/bin/env node
// Regenerates packages/perault-sdk/src/abi.ts from Foundry's build output, so the SDK's ABI
// can never drift from contracts/src/SpendVault.sol. Run after `forge build`:
//   node tools/gen-sdk-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = JSON.parse(readFileSync(join(root, "contracts/out/SpendVault.sol/SpendVault.json"), "utf8"));
const out = join(root, "packages/perault-sdk/src/abi.ts");

writeFileSync(
  out,
  `// GENERATED by tools/gen-sdk-abi.mjs from contracts/out/SpendVault.sol/SpendVault.json. Do not edit.\n` +
    `export const spendVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`wrote ${out} (${artifact.abi.length} entries)`);
